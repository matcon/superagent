"""
core/contract_spec.py - Formal Specification & API Contract Engine for SuperAgent
Synthesizes Design-by-Contract (DbC) specifications, Pydantic schemas, and detects public interface drift.
"""

import ast
import json
from dataclasses import dataclass, field, asdict
from typing import List, Dict, Any, Optional


@dataclass
class EndpointContract:
    method: str
    path: str
    summary: str
    request_schema: Dict[str, Any]
    response_schema: Dict[str, Any]
    preconditions: List[str] = field(default_factory=list)
    postconditions: List[str] = field(default_factory=list)


@dataclass
class FormalSpec:
    title: str
    version: str
    domain_invariants: List[str]
    endpoints: List[EndpointContract] = field(default_factory=list)
    entities: Dict[str, Dict[str, str]] = field(default_factory=dict)


class ContractSpecEngine:
    """Motor de especificación formal y detección de drift de contratos."""

    @classmethod
    def create_spec_scaffold(cls, title: str, domain_invariants: Optional[List[str]] = None) -> FormalSpec:
        return FormalSpec(
            title=title,
            version="1.0.0",
            domain_invariants=domain_invariants or [
                "Los identificadores de entidades deben ser UUIDv4 inmutables",
                "Las transacciones deben ser atómicas e idempotentes",
                "Las operaciones de lectura no deben mutar el estado del sistema"
            ],
            entities={
                "User": {"id": "str (UUID)", "email": "str", "created_at": "datetime"},
            },
            endpoints=[
                EndpointContract(
                    method="GET",
                    path="/health",
                    summary="Verificación de estado del servicio",
                    request_schema={},
                    response_schema={"status": "str", "timestamp": "str"},
                    preconditions=["El servicio debe estar enlazado a un puerto TCP"],
                    postconditions=["Retorna código HTTP 200 y status 'healthy'"]
                )
            ]
        )

    @classmethod
    def export_pydantic_code(cls, spec: FormalSpec) -> str:
        """Genera código Python con Pydantic v2 a partir de la especificación. aci: ignore"""
        lines = [
            "# Auto-generated by SuperAgent ContractSpecEngine",
            "from datetime import datetime",
            "from typing import Optional, List, Dict, Any",
            "from pydantic import BaseModel, Field, EmailStr",
            ""
        ]

        for entity_name, fields in spec.entities.items():
            lines.append(f"class {entity_name}(BaseModel):")
            for fname, ftype in fields.items():
                if "email" in fname.lower():
                    lines.append(f"    {fname}: EmailStr")
                elif "datetime" in ftype.lower():
                    lines.append(f"    {fname}: datetime = Field(default_factory=datetime.utcnow)")
                elif "int" in ftype.lower():
                    lines.append(f"    {fname}: int")
                elif "bool" in ftype.lower():
                    lines.append(f"    {fname}: bool")
                else:
                    lines.append(f"    {fname}: str")
            lines.append("")

        return "\n".join(lines)

    @classmethod
    def check_interface_drift(cls, old_code: str, new_code: str) -> List[str]:
        """Detecta rotura de compatibilidad (Breaking Changes) en firmas públicas de funciones o métodos."""
        drifts = []
        try:
            old_tree = ast.parse(old_code)
            new_tree = ast.parse(new_code)
        except SyntaxError as e:
            return [f"SyntaxError al analizar versiones de código: {e}"]

        def extract_public_functions(tree: ast.AST) -> Dict[str, List[str]]:
            funcs = {}
            for node in ast.walk(tree):
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    if not node.name.startswith("_"):
                        args = [a.arg for a in node.args.args]
                        funcs[node.name] = args
            return funcs

        old_funcs = extract_public_functions(old_tree)
        new_funcs = extract_public_functions(new_tree)

        for fn_name, old_args in old_funcs.items():
            if fn_name not in new_funcs:
                drifts.append(f"BREAKING: Función pública '{fn_name}' fue eliminada.")
            else:
                new_args = new_funcs[fn_name]
                # Check removed parameters
                for arg in old_args:
                    if arg not in new_args:
                        drifts.append(f"BREAKING: Parámetro '{arg}' eliminado de la función '{fn_name}'.")

        return drifts
